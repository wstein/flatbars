// Generate / check editors/operations.json — the prelude operation table the
// editor layer's hover + completion (ADR-017) read. Mirrors gen:catalog: the
// single source is FullBars.preludeSchema, projected by FullBars.Catalog
// (`operations`), so the editor can never list an operation the engine doesn't
// know. Like the helper catalog, it imports from output/ (the spago build
// product), so run a build first.
//
//   node scripts/gen-operations.mjs            # regenerate editors/operations.json
//   node scripts/gen-operations.mjs --check    # CI: fail if it drifted from the schema
//
// Each entry carries only what the engine actually knows: name, the ADR-019 kind
// (value/inline/block, derived structurally), arity, source (registered / scoped /
// alias / synonym), the alias/synonym target (`null` otherwise), and the one-line
// `doc` from OperationDef (the single source; empty for scoped variables, which
// carry none).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { operations } from "../output/FullBars.Catalog/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, "..", "editors", "operations.json");
// A browser-importable projection of the same names for the FlatBars Lab. The
// Lab can't import editors/operations.json at runtime (production deploys only
// lab/), so its inner-token highlighter reads this vendored .mjs to build the
// `isOperation` predicate — painting helper names with the SAME vocabulary as
// the LSP / VS Code and the tutorials (the parity gate's one-contract promise).
const labFile = resolve(here, "..", "lab", "operation-names.mjs");

const data = {
  _generated: "by scripts/gen-operations.mjs from FullBars.preludeSchema — DO NOT EDIT; run `npm run gen:operations`",
  operations: operations
    .map((o) => ({ name: o.name, kind: o.kind, arity: o.arity, source: o.source, canonical: o.canonical || null, doc: o.doc || "" }))
    .sort((a, b) => a.name.localeCompare(b.name)),
};
const text = JSON.stringify(data, null, 2) + "\n";

const labNames = data.operations.map((o) => o.name);
const labText =
  "// SPDX-License-Identifier: Apache-2.0\n" +
  "//\n" +
  "// VENDORED prelude operation names for the FlatBars Lab's inner-token\n" +
  "// highlighter. A pure projection of editors/operations.json — generated by\n" +
  "// scripts/gen-operations.mjs from FullBars.preludeSchema, drift-gated by\n" +
  "// check:operations. DO NOT EDIT; run `npm run gen:operations`.\n" +
  "//\n" +
  "// The Lab can't import editors/ JSON at runtime (production deploys only lab/),\n" +
  "// so it builds the highlighter's `isOperation` predicate from this — painting\n" +
  "// helper names with the SAME vocabulary as the LSP / VS Code and the tutorials.\n" +
  "export const OPERATION_NAMES = [\n" +
  labNames.map((n) => `  ${JSON.stringify(n)},`).join("\n") +
  "\n];\n";

if (process.argv.includes("--check")) {
  const stale = (file, want) => {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {
      /* missing → stale */
    }
    return current !== want;
  };
  if (stale(outFile, text) || stale(labFile, labText)) {
    console.error(
      "✗ editors/operations.json or lab/operation-names.mjs is stale vs FullBars.preludeSchema.\n" +
        "  The prelude changed. Run `npm run gen:operations` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`✓ editors/operations.json + lab/operation-names.mjs current — ${data.operations.length} operations`);
} else {
  writeFileSync(outFile, text);
  writeFileSync(labFile, labText);
  console.log(`wrote ${outFile}\n  + ${labFile}\n  ${data.operations.length} operations projected from FullBars.preludeSchema`);
}
