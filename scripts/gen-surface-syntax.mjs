#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
//
// SINGLE-SOURCE generator for the per-surface syntax & policy deltas. The source
// of truth is shared/surface-syntax.json (authored). This derives two committed
// artifacts and a drift gate, mirroring the helper-catalog (gen:catalog) pattern:
//
//   • lab/surface-syntax.mjs           — runtime projection for the Lab's
//                                         surface-aware Reference popup (prod
//                                         deploys only lab/, so it cannot read
//                                         shared/ at runtime — hence a projection).
//   • spec/src/partials/surface-deltas.mdx — the spec's per-surface delta tables,
//                                         imported by engine/surface.mdx.
//
// The tutorials' <SurfaceDeltas> component imports the JSON source directly at
// build time (Astro), so it needs no committed projection — it cannot drift.
//
//   node scripts/gen-surface-syntax.mjs           # regenerate the artifacts
//   node scripts/gen-surface-syntax.mjs --check    # CI: fail if they drifted
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const srcFile = resolve(root, "shared", "surface-syntax.json");
const labFile = resolve(root, "lab", "surface-syntax.mjs");
const specFile = resolve(root, "spec", "src", "partials", "surface-deltas.mdx");

const src = JSON.parse(readFileSync(srcFile, "utf8"));
const surfaces = src.surfaces;

// ── lab projection ─────────────────────────────────────────────────────────
// A pure ES-module projection of the surfaces array; the Lab imports SURFACE_SYNTAX
// to render the Reference popup. Stable JSON serialization so --check is reliable.
const labText =
  "// SPDX-License-Identifier: Apache-2.0\n" +
  "//\n" +
  "// VENDORED per-surface syntax/policy deltas for the FlatBars Lab's surface-aware\n" +
  "// Reference popup. A pure projection of shared/surface-syntax.json — generated by\n" +
  "// scripts/gen-surface-syntax.mjs, drift-gated by check:surface-syntax. DO NOT EDIT;\n" +
  "// run `npm run gen:surface-syntax`. (Prod deploys only lab/, so the Lab cannot read\n" +
  "// shared/ at runtime — this projection is how the single source reaches it.)\n" +
  "export const SURFACE_SYNTAX = " +
  JSON.stringify(surfaces, null, 2) +
  ";\n";

// ── spec partial (MDX) ───────────────────────────────────────────────────────
// MDX/GFM-table escaping: prose cells entity-escape the JSX-hostile chars
// ({ } < >) and table pipes; code cells stay literal inside backticks but still
// escape the table pipe with a backslash.
const proseCell = (s) =>
  s
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("{", "&#123;")
    .replaceAll("}", "&#125;")
    .replaceAll("|", "\\|");
const codeCell = (s) => "`" + s.replaceAll("|", "\\|") + "`";

let mdx =
  "{/* Generated from shared/surface-syntax.json by scripts/gen-surface-syntax.mjs — do not edit. */}\n" +
  "{/* Regenerate with `npm run gen:surface-syntax`; CI checks it with `npm run check:surface-syntax`. */}\n";
for (const s of surfaces) {
  mdx += `\n### ${s.label}\n\n`;
  mdx += `${proseCell(s.tagline)} Truthiness: ${codeCell(s.truthiness.rule)} (falsy: ${codeCell(s.truthiness.falsy)} — ${proseCell(s.truthiness.note)}).\n\n`;
  mdx += "| Feature | Syntax | Notes |\n| --- | --- | --- |\n";
  for (const r of s.rows) {
    mdx += `| ${proseCell(r.feature)} | ${codeCell(r.syntax)} | ${proseCell(r.note)} |\n`;
  }
}

// Deep-link integrity: every surface route must resolve to a real tutorial page
// (the Lab's "Full reference →" link and the per-page reference both rely on it).
for (const s of surfaces) {
  const page = resolve(root, "tutorials", "src", "pages", s.route.replace(/^\//, "") + ".astro");
  try {
    readFileSync(page);
  } catch {
    console.error(`✗ surface "${s.id}": route ${s.route} has no tutorial page (${s.route.replace(/^\//, "")}.astro).`);
    process.exit(1);
  }
}

// ── write or check ────────────────────────────────────────────────────────────
if (process.argv.includes("--check")) {
  const labCur = readFileSync(labFile, "utf8");
  const specCur = readFileSync(specFile, "utf8");
  if (labCur !== labText || specCur !== mdx) {
    const stale = [labCur !== labText && "lab/surface-syntax.mjs", specCur !== mdx && "spec/src/partials/surface-deltas.mdx"]
      .filter(Boolean)
      .join(" + ");
    console.error(
      `✗ ${stale} is stale vs shared/surface-syntax.json.\n` +
        "  Run `npm run gen:surface-syntax` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`✓ surface-syntax artifacts current — ${surfaces.length} surfaces`);
} else {
  writeFileSync(labFile, labText);
  writeFileSync(specFile, mdx);
  console.log(`✓ wrote lab/surface-syntax.mjs + spec/src/partials/surface-deltas.mdx — ${surfaces.length} surfaces`);
}
